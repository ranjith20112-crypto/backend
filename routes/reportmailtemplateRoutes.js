// config/reportEmailTemplate.js
// ============================================================================
//  REPORT DELIVERY EMAIL
//  ----------------------------------------------------------------------
//  Builds a professional, branded HTML email and sends the generated
//  report PDF as an attachment when a Report screen row is "Finalized".
//
//  Uses nodemailer with Gmail, authenticated via the SAME env vars the
//  rest of Verifitech's backend already uses:
//
//    EMAIL_USER=aws500546@gmail.com
//    EMAIL_PASS=xxxxxxxxxxxxxxxx      <- must be a 16-character Gmail
//                                        APP PASSWORD, not the normal
//                                        Gmail account password (Gmail
//                                        rejects the account password for
//                                        SMTP login when 2FA is on, and
//                                        Google no longer allows "less
//                                        secure app" access at all).
//                                        Generate one at:
//                                        https://myaccount.google.com/apppasswords
//                                        (requires 2-Step Verification to
//                                        be turned on for the account first)
//
//  If EMAIL_USER / EMAIL_PASS are missing (or still a placeholder like
//  the "t" in a fresh .env), sending is SIMULATED instead of thrown —
//  logged to the console, check still marked finalized — so local
//  development is never blocked waiting on real Gmail credentials.
// ============================================================================

const nodemailer = require('nodemailer');
const path = require('path');
const fs = require('fs');

const LOGO_PATH = path.join(__dirname, '..', 'images', 'verifitech-logoo.png');
const LOGO_CID = 'verifitech-logo';

// A real Gmail app password is always 16 characters (letters only, no
// spaces once copied). Anything shorter — like a leftover placeholder
// value such as "t" — is treated as "not configured yet" so we fall back
// to the simulated transport instead of letting Gmail reject the login
// and throw a confusing auth error.
function hasValidEmailConfig() {
  const user = process.env.EMAIL_USER;
  const pass = process.env.EMAIL_PASS;
  return !!user && !!pass && pass.replace(/\s+/g, '').length >= 16;
}

function createTransporter(isConfigured) {
  if (!isConfigured) {
    // No usable Gmail credentials yet — nodemailer's JSON transport never
    // dials out anywhere, so Finalize & Send / Resend can't fail with a
    // connection or auth error while EMAIL_PASS is still a placeholder.
    return nodemailer.createTransport({ jsonTransport: true });
  }

  return nodemailer.createTransport({
    service: 'gmail',
    auth: {
      user: process.env.EMAIL_USER,
      pass: process.env.EMAIL_PASS,
    },
  });
}

const fmtDate = (d) => {
  if (!d) return '';
  const dt = new Date(d);
  if (Number.isNaN(dt.getTime())) return '';
  return dt.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
};

