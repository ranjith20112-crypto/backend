// sendReportDeliveryEmail({ to, candidateName, bgvRef, checkType, subType,
//   clientName, finalStatus, pdfBuffer, fileName })
// Returns { success, messageId, simulated }.
async function sendReportDeliveryEmail({
  to, candidateName, bgvRef, checkType, subType, clientName, finalStatus, pdfBuffer, fileName,
}) {
  if (!to) throw new Error('A client email address is required.');
  if (!pdfBuffer) throw new Error('No PDF was provided to attach.');

  const isConfigured = hasValidEmailConfig();
  const transporter = createTransporter(isConfigured);

  const attachments = [
    {
      filename: fileName || 'Verification_Report.pdf',
      content: pdfBuffer,
      contentType: 'application/pdf',
    },
  ];

  if (fs.existsSync(LOGO_PATH)) {
    attachments.push({
      filename: 'verifitech-logo.png',
      path: LOGO_PATH,
      cid: LOGO_CID,
    });
  }

  const html = buildReportEmailHtml({ candidateName, bgvRef, checkType, subType, clientName, finalStatus });

  const info = await transporter.sendMail({
    from: process.env.EMAIL_FROM || `"Verifitech Reports" <${process.env.EMAIL_USER || 'reports@verifitech.com'}>`,
    to,
    subject: `Verification Report — ${candidateName || 'Candidate'} (${bgvRef || ''})`,
    html,
    attachments,
  });

  if (!isConfigured) {
    console.log('\n📧 [DEV MODE] EMAIL_USER / EMAIL_PASS not set (or EMAIL_PASS is a placeholder) — email simulated, not actually sent.');
    console.log(`    Would have sent to: ${to}`);
    console.log(`    Subject: Verification Report — ${candidateName || 'Candidate'} (${bgvRef || ''})`);
    console.log('    Set EMAIL_USER to a Gmail address and EMAIL_PASS to a 16-character Gmail');
    console.log('    App Password (https://myaccount.google.com/apppasswords) to send real emails.\n');
  }

  return { success: true, messageId: info.messageId, simulated: !isConfigured };
}

module.exports = { sendReportDeliveryEmail, buildReportEmailHtml };